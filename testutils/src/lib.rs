// ─── MockMultisig ─────────────────────────────────────────────────────────────

pub mod mock_multisig {
    use soroban_sdk::{contract, contractimpl, contracttype, Address, Env, Symbol, Val, Vec};

    #[contracttype]
    #[derive(Clone, Debug, Eq, PartialEq)]
    pub struct MultisigConfig {
        pub threshold: u32,
    }

    #[contracttype]
    #[derive(Clone)]
    pub enum MultisigKey {
        Config,
        Signer(Address),
        ActionSig(u64, Address),
        ActionCount(u64),
        NextAction,
    }

    #[contract]
    pub struct MockMultisig;

    #[contractimpl]
    impl MockMultisig {
        pub fn initialize(env: Env, threshold: u32) {
            if env.storage().instance().has(&MultisigKey::Config) {
                panic!("already initialized");
            }
            if threshold == 0 {
                panic!("threshold must be positive");
            }
            env.storage()
                .instance()
                .set(&MultisigKey::Config, &MultisigConfig { threshold });
            env.storage()
                .instance()
                .set(&MultisigKey::NextAction, &0u64);
        }

        pub fn add_signer(env: Env, signer: Address) {
            env.storage()
                .persistent()
                .set(&MultisigKey::Signer(signer), &true);
        }

        pub fn propose(env: Env, proposer: Address) -> u64 {
            proposer.require_auth();
            let id: u64 = env
                .storage()
                .instance()
                .get(&MultisigKey::NextAction)
                .unwrap_or(0);
            env.storage()
                .instance()
                .set(&MultisigKey::NextAction, &(id + 1));
            env.storage()
                .instance()
                .set(&MultisigKey::ActionCount(id), &0u32);
            id
        }

        pub fn sign(env: Env, signer: Address, action_id: u64) {
            signer.require_auth();
            let is_signer: bool = env
                .storage()
                .persistent()
                .get(&MultisigKey::Signer(signer.clone()))
                .unwrap_or(false);
            if !is_signer {
                panic!("not a signer");
            }
            let already: bool = env
                .storage()
                .persistent()
                .get(&MultisigKey::ActionSig(action_id, signer.clone()))
                .unwrap_or(false);
            if already {
                panic!("already signed");
            }
            env.storage()
                .persistent()
                .set(&MultisigKey::ActionSig(action_id, signer), &true);
            let count: u32 = env
                .storage()
                .instance()
                .get(&MultisigKey::ActionCount(action_id))
                .unwrap_or(0);
            env.storage()
                .instance()
                .set(&MultisigKey::ActionCount(action_id), &(count + 1));
        }

        pub fn execute(
            env: Env,
            action_id: u64,
            target: Address,
            function: Symbol,
            args: Vec<Val>,
        ) -> Val {
            let config: MultisigConfig = env
                .storage()
                .instance()
                .get(&MultisigKey::Config)
                .expect("not initialized");
            let count: u32 = env
                .storage()
                .instance()
                .get(&MultisigKey::ActionCount(action_id))
                .unwrap_or(0);
            if count < config.threshold {
                panic!("threshold not met");
            }
            env.invoke_contract(&target, &function, args)
        }

        pub fn sig_count(env: Env, action_id: u64) -> u32 {
            env.storage()
                .instance()
                .get(&MultisigKey::ActionCount(action_id))
                .unwrap_or(0)
        }

        pub fn config(env: Env) -> MultisigConfig {
            env.storage()
                .instance()
                .get(&MultisigKey::Config)
                .expect("not initialized")
        }
    }
}

