/// Common test environment with a deployed mock governance and token.
pub struct GovernanceScenario {
    pub env: Env,
    pub token: MockToken,
    pub gov_addr: Address,
    pub admin: Address,
}

impl GovernanceScenario {
    pub fn gov(&self) -> MockGovernanceClient<'_> {
        MockGovernanceClient::new(&self.env, &self.gov_addr)
    }
}

pub fn governance_scenario() -> GovernanceScenario {
    let env = Env::default();
    env.mock_all_auths();

    let admin = Address::generate(&env);
    let token_owner = Address::generate(&env);
    let token = MockToken::deploy(&env, &token_owner);

    let gov_id = env.register_contract(None, MockGovernance);
    MockGovernanceClient::new(&env, &gov_id).initialize(&admin);

    GovernanceScenario { env, token, gov_addr: gov_id, admin }
}

