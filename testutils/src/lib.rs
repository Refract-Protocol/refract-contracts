/// Common test environment with a deployed mock multisig and token.
pub struct MultisigScenario {
    pub env: Env,
    pub token: MockToken,
    pub multisig_addr: Address,
    pub signers: Vec<Address>,
    pub threshold: u32,
}

impl MultisigScenario {
    pub fn multisig(&self) -> MockMultisigClient<'_> {
        MockMultisigClient::new(&self.env, &self.multisig_addr)
    }
}

pub fn multisig_scenario(n_signers: u32, threshold: u32) -> MultisigScenario {
    let env = Env::default();
    env.mock_all_auths();

    let token_owner = Address::generate(&env);
    let token = MockToken::deploy(&env, &token_owner);

    let ms_id = env.register_contract(None, MockMultisig);
    let ms_client = MockMultisigClient::new(&env, &ms_id);
    ms_client.initialize(&threshold);

    let mut signers: Vec<Address> = Vec::new(&env);
    for _ in 0..n_signers {
        let s = Address::generate(&env);
        ms_client.add_signer(&s);
        signers.push_back(s);
    }

    MultisigScenario {
        env,
        token,
        multisig_addr: ms_id,
        signers,
        threshold,
    }
}

