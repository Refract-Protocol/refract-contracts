// ─── Smoke tests ─────────────────────────────────────────────────────────────

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn mock_token_mint_and_balance() {
        let env = Env::default();
        env.mock_all_auths();
        let owner = Address::generate(&env);
        let token = MockToken::deploy(&env, &owner);
        let recipient = Address::generate(&env);
        token.mint(&env, &recipient, 10_000_000);
        assert_eq!(token.balance(&env, &recipient), 10_000_000);
    }

    #[test]
    fn mock_governance_admin_executes() {
        let s = governance_scenario();
        assert_eq!(s.gov().admin(), s.admin);
    }

    #[test]
    fn mock_timelock_controller_and_delay() {
        let s = timelock_scenario(3600);
        assert_eq!(s.timelock().controller(), s.controller);
        assert_eq!(s.timelock().delay(), 3600u64);
    }

    #[test]
    fn mock_multisig_threshold_and_config() {
        let s = multisig_scenario(3, 2);
        assert_eq!(s.multisig().config().threshold, 2u32);
        assert_eq!(s.signers.len(), 3);
    }

    #[test]
    fn multisig_sig_count_increments_per_signer() {
        let s = multisig_scenario(3, 2);
        let ms = s.multisig();
        let proposer = s.signers.get(0).unwrap();
        let action_id = ms.propose(&proposer);
        assert_eq!(ms.sig_count(&action_id), 0u32);
        ms.sign(&s.signers.get(0).unwrap(), &action_id);
        assert_eq!(ms.sig_count(&action_id), 1u32);
        ms.sign(&s.signers.get(1).unwrap(), &action_id);
        assert_eq!(ms.sig_count(&action_id), 2u32);
    }

    #[test]
    fn full_stack_scenario_builds() {
        let s = full_stack_scenario();
        assert_eq!(s.timelock().delay(), 0u64);
        assert_eq!(s.timelock().controller(), s.controller);
    }
}
