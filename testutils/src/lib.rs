//! # refract-testutils
//!
//! Shared test infrastructure for the Refract contracts suite.
//!
//! ## Contents
//!
//! * **`mock_token`** — a minimal SEP-41-compatible token helper backed by
//!   `soroban-sdk`'s `register_stellar_asset_contract_v2`.
//! * **`mock_governance`** — stub governance contract (zero voting period).
//! * **`mock_timelock`** — stub timelock contract (configurable delay).
//! * **`mock_multisig`** — stub n-of-m multisig contract.
//! * **Scenario builders** — `governance_scenario`, `timelock_scenario`,
//!   `multisig_scenario`, `full_stack_scenario`.

// This crate is testutils-only: the `testutils` feature is always active.
// It compiles as `rlib` only and must never be a `cdylib`.

use soroban_sdk::{testutils::Address as _, Address, Env, Vec};

pub use soroban_sdk::token::{Client as TokenClient, StellarAssetClient};

// ─── MockToken ────────────────────────────────────────────────────────────────

/// SAC-backed mock token with convenience helpers.
/// Stores only the token address; clients are created on demand so there
/// is no lifetime tie to the `Env`.
pub struct MockToken {
    pub address: Address,
}

impl MockToken {
    pub fn deploy(env: &Env, token_admin: &Address) -> Self {
        let sac = env.register_stellar_asset_contract_v2(token_admin.clone());
        MockToken { address: sac.address() }
    }

    pub fn mint(&self, env: &Env, recipient: &Address, amount: i128) {
        StellarAssetClient::new(env, &self.address).mint(recipient, &amount);
    }

    pub fn balance(&self, env: &Env, address: &Address) -> i128 {
        TokenClient::new(env, &self.address).balance(address)
    }
}

// ─── MockGovernance ───────────────────────────────────────────────────────────

pub mod mock_governance {
    use soroban_sdk::{contract, contractimpl, contracttype, Address, Env, Symbol, Val, Vec};

    #[contracttype]
    #[derive(Clone)]
    pub enum GovKey {
        Admin,
    }

    #[contract]
    pub struct MockGovernance;

    #[contractimpl]
    impl MockGovernance {
        pub fn initialize(env: Env, admin: Address) {
            if env.storage().instance().has(&GovKey::Admin) {
                panic!("already initialized");
            }
            env.storage().instance().set(&GovKey::Admin, &admin);
        }

        pub fn execute(
            env: Env,
            caller: Address,
            target: Address,
            function: Symbol,
            args: Vec<Val>,
        ) -> Val {
            caller.require_auth();
            let admin: Address = env
                .storage()
                .instance()
                .get(&GovKey::Admin)
                .expect("not initialized");
            if caller != admin {
                panic!("unauthorized");
            }
            env.invoke_contract(&target, &function, args)
        }

        pub fn admin(env: Env) -> Address {
            env.storage()
                .instance()
                .get(&GovKey::Admin)
                .expect("not initialized")
        }
    }
}

pub use mock_governance::MockGovernance;
